/**
 * chat-detail.html currently does not ship the Builder workflow shell or scripts.
 * Mount the host DOM + load the product modules so STEP 003–005 can exercise the
 * real reveal UI without editing Talk/Builder source.
 */
async function ensureBuilderWorkflowMounted(page, threadId) {
  await page.evaluate(() => {
    if (document.getElementById("talkBuilderWorkflowPanel")) return;
    const shell = document.createElement("div");
    shell.id = "talkBuilderWorkflowPanel";
    shell.className = "talk-builder-workflow";
    shell.hidden = true;
    shell.innerHTML =
      '<div class="talk-builder-workflow__head">' +
      '<span id="talkBuilderWorkflowKind" class="talk-builder-workflow__kind"></span>' +
      '<a id="talkBuilderWorkflowOpenBuilder" class="talk-builder-workflow__builder-link" hidden href="#">Builder</a>' +
      "</div>" +
      '<div id="talkBuilderWorkflowMeta" class="talk-builder-workflow__meta"></div>' +
      '<div id="talkBuilderContactRevealHost" hidden></div>' +
      '<div id="talkBuilderWorkflowStatusRow" class="talk-builder-workflow__status-row" hidden>' +
      '<span id="talkBuilderWorkflowStatusBadge" class="chat-pill"></span>' +
      '<div id="talkBuilderWorkflowActions" hidden></div>' +
      '<p id="talkBuilderWorkflowStatusHint" hidden></p>' +
      "</div>" +
      '<div id="talkBuilderCompletionReportHost" hidden></div>';
    const anchor =
      document.getElementById("chatPeerHeader") ||
      document.getElementById("chatMessages") ||
      document.querySelector("main") ||
      document.body;
    if (anchor.parentNode) {
      anchor.parentNode.insertBefore(shell, anchor.nextSibling);
    } else {
      document.body.appendChild(shell);
    }
  });

  const scripts = [
    "builder/builder-billing-policy.js",
    "builder/builder-contact-reveal.js",
    "talk-builder-workflow.js",
  ];
  const origin = base.endsWith("/") ? base : `${base}/`;
  for (const src of scripts) {
    const tagged = await page.evaluate(
      (path) => Boolean(document.querySelector(`script[data-talk-ui-review-src="${path}"]`)),
      src
    );
    if (tagged) continue;
    await page.addScriptTag({ url: new URL(src, origin).href });
    await page.evaluate((path) => {
      const nodes = [...document.querySelectorAll("script[src]")];
      const match = nodes.find((el) => String(el.src || "").includes(path));
      if (match) match.setAttribute("data-talk-ui-review-src", path);
    }, src);
  }

  await page.waitForFunction(() => Boolean(window.TasuTalkBuilderWorkflow?.apply), null, {
    timeout: 10000,
  });

  const applied = await page.evaluate((tid) => {
    const Wf = window.TasuTalkBuilderWorkflow;
    if (!Wf?.apply) return { ok: false, reason: "TasuTalkBuilderWorkflow.apply missing" };
    const fromStore = (window.TasuChatThreadStore?.readAll?.() || []).find((t) => String(t.id) === tid);
    const fromLs = JSON.parse(localStorage.getItem("tasful_chat_threads") || "[]").find(
      (t) => String(t.id) === tid
    );
    const thread = fromStore || fromLs || null;
    if (!thread) return { ok: false, reason: `thread not found: ${tid}` };
    Wf.wireUiOnce?.();
    Wf.apply(thread);
    const kind = Wf.resolveBuilderThreadKind?.(thread) || "";
    return {
      ok: true,
      kind,
      role: Wf.resolveViewerRole?.() || "",
      needsGate: Boolean(Wf.needsContactRevealGate?.(thread, kind)),
      partnerId: String(thread.contactTargetId || thread.partner?.id || ""),
      partnerName: String(thread.partner?.displayName || thread.listingTitle || ""),
    };
  }, threadId);

  if (!applied.ok) {
    throw new Error(`ensureBuilderWorkflowMounted failed: ${applied.reason}`);
  }
  return applied;
}

async function collectRevealDiagnostics(page, stepName) {
  const diagnostics = await page.evaluate(() => {
    const buttons = [...document.querySelectorAll("button")].slice(0, 40).map((button) => ({
      text: (button.textContent || "").trim().slice(0, 80),
      ariaLabel: button.getAttribute("aria-label") || "",
      dataAttrs: [...button.attributes]
        .filter((attr) => attr.name.startsWith("data-"))
        .reduce((acc, attr) => {
          acc[attr.name] = attr.value;
          return acc;
        }, {}),
    }));
    const revealHints = [...document.querySelectorAll("body *")]
      .filter((el) => {
        if (el.children && el.children.length > 3) return false;
        return /開示|連絡先|550/.test(el.textContent || "");
      })
      .slice(0, 12)
      .map((el) => ({
        tag: el.tagName.toLowerCase(),
        text: (el.textContent || "").trim().slice(0, 80),
        id: el.id || "",
      }));
    return {
      url: location.href,
      hasWorkflowApi: Boolean(window.TasuTalkBuilderWorkflow),
      hasRevealApi: Boolean(window.TasuBuilderContactReveal),
      panelPresent: Boolean(document.getElementById("talkBuilderWorkflowPanel")),
      hostPresent: Boolean(document.getElementById("talkBuilderContactRevealHost")),
      hostHidden: document.getElementById("talkBuilderContactRevealHost")?.hidden ?? null,
      revealBtnCount: document.querySelectorAll("[data-builder-contact-reveal]").length,
      openPanelCount: document.querySelectorAll(".builder-contact-reveal--open").length,
      builderDataAttrs: [
        ...new Set(
          [...document.querySelectorAll("*")].flatMap((element) =>
            [...element.attributes]
              .map((attr) => attr.name)
              .filter((name) => name.startsWith("data-builder-"))
          )
        ),
      ].slice(0, 40),
      buttons,
      revealHints,
    };
  });
  console.log(`[reveal-diag] ${stepName}: ${JSON.stringify(diagnostics)}`);
  return diagnostics;
}

async function prepareWorkerBeforeReveal(page) {
  const mounted = await ensureBuilderWorkflowMounted(page, WORKER_THREAD_ID);
  console.log(`[reveal-mount] worker-before-reveal: ${JSON.stringify(mounted)}`);
  await collectRevealDiagnostics(page, "worker-before-reveal");
  await page.locator(REVEAL_HOST_SEL).waitFor({ state: "visible", timeout: 15000 });
  const btn = page.locator(REVEAL_BTN_SEL).first();
  await btn.waitFor({ state: "visible", timeout: 10000 });
  if (!(await btn.isEnabled())) {
    throw new Error("STEP 003: reveal action is disabled");
  }
}

async function prepareWorkerAfterReveal(page) {
  const mounted = await ensureBuilderWorkflowMounted(page, WORKER_THREAD_ID);
  console.log(`[reveal-mount] worker-after-reveal: ${JSON.stringify(mounted)}`);
  await collectRevealDiagnostics(page, "worker-after-reveal");

  if (mounted.partnerId && mounted.partnerId !== "w1") {
    throw new Error(`STEP 004: unexpected contact target ${mounted.partnerId}`);
  }
  if (!mounted.needsGate) {
    throw new Error("STEP 004: expected pre-reveal gate state (needsContactRevealGate=false)");
  }

  const revealButton = page.locator(REVEAL_BTN_SEL).first();
  await revealButton.waitFor({ state: "visible", timeout: 15000 });
  if (!(await revealButton.isEnabled())) {
    throw new Error("STEP 004: reveal action is disabled");
  }
  const box = await revealButton.boundingBox();
  if (!box || box.width <= 0 || box.height <= 0) {
    throw new Error("STEP 004: reveal button has no bounding box");
  }

  page.once("dialog", (d) => d.accept());
  await revealButton.click();

  await page.locator(REVEAL_OPEN_SEL).waitFor({ state: "visible", timeout: 15000 });
  await page.waitForFunction(
    () => {
      const open = document.querySelector(".builder-contact-reveal--open");
      const btn = document.querySelector("#talkBuilderContactRevealHost [data-builder-contact-reveal]");
      const badge = open?.querySelector(".builder-contact-reveal__badge");
      return Boolean(open && !btn && badge && /開示済み/.test(badge.textContent || ""));
    },
    null,
    { timeout: 15000 }
  );
}

async function prepareAdminTalk(page) {
  const mounted = await ensureBuilderWorkflowMounted(page, ADMIN_THREAD_ID);
  console.log(`[reveal-mount] admin-talk: ${JSON.stringify(mounted)}`);
  await page.locator(WORKFLOW_PANEL_SEL).waitFor({ state: "visible", timeout: 15000 });
}

async function main() {
  console.log(`\n=== Talk UI review capture ===`);
  console.log(`Base: ${base}`);
  console.log(`Output: reports/ui-review/${FEATURE}/\n`);

  const session = createUiReviewSession(FEATURE, { baseUrl: base });

  await withPlaywrightBrowser(async (browser) => {
    const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
    const stagingHits = await installTalkReviewStagingIsolation(page);
    await seedReviewThreads(page);

    await session.captureStep(page, browser, {
      slug: "talk-home",
      label: "Talk ホーム（友達一覧）",
      url: buildLocalPageUrl(base, "talk-home.html?tab=chat"),
      beforeGoto: reviewBeforeGoto,
      waitFor: FRIEND_ROW_SEL,
      prepare: async (p) => {
        await p.locator(FRIEND_ROW_SEL).first().waitFor({ state: "visible", timeout: 20000 });
      },
    });

    await session.captureStep(page, browser, {
      slug: "profile-card",
      label: "プロフィールカード（開いた状態）",
      url: buildLocalPageUrl(base, "talk-home.html?tab=chat"),
      viewports: ["1280", "768", "390"],
      beforeGoto: reviewBeforeGoto,
      prepare: async (p) => {
        await openFriendProfileCard(p);
        await p.waitForTimeout(350);
      },
    });

    await session.captureStep(page, browser, {
      slug: "worker-before-reveal",
      label: "ワーカー検索 · 開示前（550円ゲート）",
      url: chatUrl("verify-worker-contact", { builderRole: "user" }),
      beforeGoto: reviewBeforeGoto,
      waitFor: "#chatPeerHeader",
      prepare: prepareWorkerBeforeReveal,
    });

    await session.captureStep(page, browser, {
      slug: "worker-after-reveal",
      label: "ワーカー検索 · 開示後（連絡先 + 電話）",
      url: chatUrl("verify-worker-contact", { builderRole: "user" }),
      viewports: ["1280", "768", "390"],
      beforeGoto: reviewBeforeGoto,
      waitFor: "#chatPeerHeader",
      prepare: prepareWorkerAfterReveal,
    });

    await session.captureStep(page, browser, {
      slug: "admin-talk",
      label: "運営案件 Talk（ヘッダーアクション非表示）",
      url: chatUrl("verify-admin-partner", { builderFlow: "ops_partner", builderRole: "partner" }),
      beforeGoto: reviewBeforeGoto,
      waitFor: "#chatPeerHeader",
      prepare: prepareAdminTalk,
    });

    await session.captureStep(page, browser, {
      slug: "normal-chat",
      label: "通常 Talk（ヘッダーアクション表示）",
      url: buildLocalPageUrl(base, "chat-detail.html?thread=verify-normal-chat"),
      beforeGoto: reviewBeforeGoto,
      waitFor: "#chatPeerHeader",
      viewports: ["1280", "390"],
    });

    await stagingHits.collectRealtimeStats();
    reportTalkReviewStagingIsolation(stagingHits);
    await page.close();
  }, { headless: true });

  const { ok, reportPath } = session.writeReport({ baseUrl: base });
  await closeAllBrowsers();

  if (!ok) {
    console.error("\nFAIL: console errors detected — see report");
    process.exitCode = 1;
    return;
  }
  console.log("\nPASS talk UI review capture");
  console.log(`Report: ${reportPath}`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
