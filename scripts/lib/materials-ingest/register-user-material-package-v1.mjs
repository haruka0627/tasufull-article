/**
 * User Material register — reuses existing SFX package writer + ingest adapters.
 * Trusted TASFUL Account user_id only. No duplicate package engine.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  PRODUCT_SOURCE,
  validateUserListing,
} from "../materials-user-digital-products/contract.mjs";
import { validateUserUpload } from "../materials-user-digital-products/security.mjs";
import {
  expectedFilenames,
  preparePackageTmp,
  promotePackageFromTmp,
  writeSoundToTmp,
} from "../../../SFX-AutoGenerator/lib/package.js";
import { synthesizeSfx, variationSeed } from "../../../SFX-AutoGenerator/lib/presets.js";
import { adaptSfxPackage } from "./adapters/flat-package.mjs";
import { loadIngestConfig } from "./common.mjs";
import { toPublicItem } from "./download-fields.mjs";
import {
  CANONICAL_QA_USER_ID,
  OWNERSHIP_SOURCE,
  resolveTrustedWriteCreatorUserId,
} from "./creator-ownership-write-v1.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");

export { CANONICAL_QA_USER_ID };

export function registerUserSfxPackage(input = {}) {
  const slug = String(input.slug || "qa-owner-write-sfx").trim();
  const packageDir = path.resolve(String(input.packageDir || path.join(ROOT, "reports", "ops", "materials-creator-ownership-write-path-v1", "qa-package", slug)));
  const authenticatedUserId = String(input.authenticatedUserId || "").trim();
  const claimedUserId = input.claimedUserId == null ? "" : String(input.claimedUserId).trim();
  const promptText = String(input.promptText || "short QA ownership write click");
  const categoryPath = Array.isArray(input.categoryPath) && input.categoryPath.length
    ? input.categoryPath
    : ["テロップ", "pop"];
  const title = String(input.title || "所有権書き込み確認クリック音");
  const fileName = `${slug}-001.wav`;

  const listing = validateUserListing({
    source: PRODUCT_SOURCE.USER,
    creator_user_id: authenticatedUserId,
    subtype: "audio_sfx",
    category_id: "sfx",
    distribution: "free",
  });
  if (!listing.ok) {
    return { ok: false, stage: "validateUserListing", ...listing };
  }

  const trust = resolveTrustedWriteCreatorUserId({
    source: OWNERSHIP_SOURCE.USER,
    authenticatedUserId,
    claimedUserId,
  });
  if (!trust.ok) {
    return { ok: false, stage: "resolveTrustedWriteCreatorUserId", ...trust };
  }

  const expected = expectedFilenames(slug, 1);
  const synth = synthesizeSfx({
    presetId: "pop",
    seed: variationSeed(slug, 1),
    sampleRate: 48000,
    targetPeakDbfs: -1,
  });
  const tmp = preparePackageTmp(packageDir, { reset: true });
  const written = writeSoundToTmp(tmp, expected[0], synth.L, synth.R, {
    sampleRate: 48000,
    bitDepth: 16,
    channels: 2,
  });

  const upload = validateUserUpload({
    subtype: "audio_sfx",
    file_name: fileName,
    byte_size: written.bytes,
    execution_mode: "download",
  });
  if (!upload.ok) {
    return { ok: false, stage: "validateUserUpload", ...upload };
  }

  let metadata;
  try {
    metadata = promotePackageFromTmp(packageDir, {
      expectedFiles: expected,
      promptText,
      slug,
      categoryPath,
      sampleRate: 48000,
      bitDepth: 16,
      channels: 2,
      presetId: "pop",
      fileStats: [{ variation: 1, bytes: written.bytes, filename: expected[0] }],
      extraMetadata: {
        title,
        product_source: PRODUCT_SOURCE.USER,
        __ownership: {
          source: OWNERSHIP_SOURCE.USER,
          authenticatedUserId,
        },
        ...(claimedUserId ? { creator_user_id: claimedUserId } : {}),
      },
    });
  } catch (err) {
    return {
      ok: false,
      stage: "promotePackageFromTmp",
      reason: err?.code || err?.message || String(err),
      error: String(err?.message || err),
    };
  }

  const metaPath = path.join(packageDir, "metadata.json");
  return {
    ok: true,
    packageDir,
    metaPath,
    wavPath: path.join(packageDir, expected[0]),
    downloadFilename: expected[0],
    creator_user_id: metadata.creator_user_id,
    metadata,
    listing,
  };
}

export function ingestRegisteredSfxPackage(packageDir) {
  const metaPath = path.join(packageDir, "metadata.json");
  const meta = JSON.parse(fs.readFileSync(metaPath, "utf8"));
  const cfg = loadIngestConfig();
  const adapted = adaptSfxPackage(metaPath, meta, cfg);
  return {
    meta,
    items: (adapted.items || []).map((item) => toPublicItem(item)),
    invalid: adapted.invalid || [],
  };
}

export function writeServedPublicIndexJs(index) {
  const payload = {
    ...index,
    itemCount: Array.isArray(index.items) ? index.items.length : 0,
  };
  return (
    "/* generated by scripts/build-materials-index.mjs — do not edit */\n" +
    "(function (global) {\n" +
    '  "use strict";\n' +
    `  global.TASFUL_MATERIALS_INDEX = ${JSON.stringify(payload)};\n` +
    "})(typeof window !== \"undefined\" ? window : globalThis);\n"
  );
}
