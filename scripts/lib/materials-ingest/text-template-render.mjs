function greeting(tone, kind) {
  if (kind === "email") {
    if (tone === "formal") return "拝啓\n時下ますますご清栄のこととお慶び申し上げます。";
    if (tone === "friendly") return "[担当者名]さん\n\nお世話になります。[会社名]の[氏名]です。";
    if (tone === "casual") return "[担当者名]さん\n\nご連絡です。";
    if (tone === "concise") return "[担当者名]様\n\n件名の件です。";
    if (tone === "warm") return "[担当者名]様\n\nいつもありがとうございます。[会社名]の[氏名]です。";
    if (tone === "professional") return "[担当者名]様\n\n[会社名]の[氏名]です。下記ご確認ください。";
    return "[担当者名]様\n\nいつもお世話になっております。[会社名]の[氏名]です。";
  }
  if (kind === "sns") {
    if (tone === "casual") return "きょうのお知らせです。";
    if (tone === "concise") return "お知らせ。";
    if (tone === "warm") return "いつも見てくださってありがとうございます。";
    if (tone === "professional") return "[会社名]からのご案内です。";
    return "こんにちは。[会社名]です。";
  }
  if (kind === "ad") {
    if (tone === "casual") return "これ、使ってみて。";
    if (tone === "concise") return "今すぐ。";
    if (tone === "professional") return "[課題]を、手順どおりに片付ける。";
    return "[商品名]で、次の一手を決める。";
  }
  if (tone === "concise") return "要点だけ書きます。";
  if (tone === "formal") return "ご案内申し上げます。";
  return "ご案内です。";
}

function closing(tone, kind) {
  if (kind === "email") {
    if (tone === "formal") return "まずはご連絡まで。\n敬具\n\n[会社名]\n[氏名]\n[問い合わせ先]";
    if (tone === "concise") return "以上です。\n[氏名] / [問い合わせ先]";
    if (tone === "friendly") return "またご連絡ください。\n[氏名]";
    return "ご確認のほどよろしくお願いいたします。\n[会社名] [氏名]\n[問い合わせ先]";
  }
  if (kind === "sns") return "詳細は [URL]";
  if (kind === "ad") return "[URL]";
  return "お問い合わせ：[問い合わせ先]";
}

function trimByLength(body, length, spec) {
  const lines = body.split("\n").filter((l, i, arr) => !(l === "" && arr[i - 1] === ""));
  if (length === "short") {
    return lines.slice(0, Math.min(6, lines.length)).join("\n");
  }
  const purpose = `用途：${spec.use_case || "general"} / ${spec.subcategory || "template"}`;
  if (length === "long") {
    return `${body}\n\n${purpose}\n補足：[日時] 時点の案内です。変更があれば [問い合わせ先] までご連絡ください。`;
  }
  return `${body}\n\n${purpose}`;
}

