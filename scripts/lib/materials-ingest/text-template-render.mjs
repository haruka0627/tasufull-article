function collectVariables(text) {
  const found = [...String(text).matchAll(/\[[^[\]]{1,40}\]/g)].map((m) => m[0]);
  const out = [];
  const seen = new Set();
  for (const v of [...TEXT_DEFAULT_VARIABLES, ...found]) {
    if (seen.has(v)) continue;
    seen.add(v);
    out.push(v);
  }
  return out;
}

export function renderTextTemplate(spec) {
  const g = getTextGenre(spec.genre);
  const sg = getTextSubgenre(spec.subcategory)?.subgenre;
  const kind = spec.text_type || g?.text_types?.[0] || "email";
  const tone = spec.tone || "polite";
  const length = spec.length || "medium";
  const core = BODIES[spec.subcategory] || `${sg?.label_ja || "文例"}のひな型です。\n対象：[対象]\n期限：[期限]`;
  const open = greeting(tone, kind);
  const close = closing(tone, kind);
  let content = `${open}\n\n${core}\n\n${close}`;
  content = trimByLength(content, length, spec);
  const blocked = isProfessionalTextBlocked(content);
  const template_variables = collectVariables(content);
  return {
    title: spec.title,
    description: spec.description,
    content,
    template_variables,
    opening_key: `${kind}:${tone}`,
    structure_key: spec.structure_key || spec.subcategory,
    professional_blocked: blocked,
    length_label: TEXT_LENGTHS[length]?.label_ja,
    tone_label: TEXT_TONES[tone]?.label_ja,
  };
}
