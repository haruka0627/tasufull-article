  const DEFAULT_LOCALE = "ja-JP";
  /** Existing TASFUL UI locale preference (Short Video editor). Shared across surfaces. */
  const STORAGE_KEY = "tasful.shortVideo.uiLocale";

  function registerDict(locale, entries) {
    const loc = normalize(locale) || String(locale || "").trim();
    if (!loc || !entries || typeof entries !== "object") return loc;
    if (!DICT[loc]) DICT[loc] = {};
    Object.assign(DICT[loc], entries);
    return loc;
  }

  function getStoredLocale() {
    try {
      const saved = global.localStorage && global.localStorage.getItem(STORAGE_KEY);
      return normalize(saved) || DEFAULT_LOCALE;
    } catch (_) {
      return DEFAULT_LOCALE;
    }
  }

  function setStoredLocale(code) {
    const loc = normalize(code) || DEFAULT_LOCALE;
    try {
      if (global.localStorage) global.localStorage.setItem(STORAGE_KEY, loc);
    } catch (_) {}
    return loc;
  }

  function normalize(code) {
    const raw = String(code || "").trim();
    if (DICT[raw]) return raw;
    const lower = raw.toLowerCase();
    if (lower.startsWith("ja")) return "ja-JP";
    if (lower.startsWith("en")) return "en";
    if (lower.startsWith("ko")) return "ko-KR";
    if (lower === "zh-tw" || lower === "zh-hant") return "zh-TW";
    return null;
  }

  function resolve(requested) {
    const first = normalize(requested);
    const chain = [];
    if (first) chain.push(first);
    for (const fb of ["en", "ja-JP"]) {
      if (!chain.includes(fb)) chain.push(fb);
    }
    return { locale: chain[0], chain };
  }

  function t(key, locale) {
    const { chain } = resolve(locale || DEFAULT_LOCALE);
    for (const loc of chain) {
      if (DICT[loc] && DICT[loc][key] != null) return DICT[loc][key];
    }
    return key;
  }

  function apply(root, locale) {
    const { locale: loc } = resolve(locale);
    root.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (key) el.textContent = t(key, loc);
    });
    root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const key = el.getAttribute("data-i18n-placeholder");
      if (key) el.setAttribute("placeholder", t(key, loc));
    });
    root.querySelectorAll("[data-i18n-title]").forEach((el) => {
      const key = el.getAttribute("data-i18n-title");
      if (key) el.setAttribute("title", t(key, loc));
    });
    document.documentElement.lang = loc === "zh-TW" ? "zh-Hant" : loc.split("-")[0];
    return loc;
  }

  global.TasuShortVideoI18n = {
    LOCALES,
    SAMPLES,
    DEFAULT_LOCALE,
    STORAGE_KEY,
    registerDict,
    getStoredLocale,
    setStoredLocale,
    resolve,
    t,
    apply,
  };
